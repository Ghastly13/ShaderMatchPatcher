using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Assets;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;

namespace ShaderMatchPatcher;

public static class Program
{
    private static Lazy<Settings> _settings = null!;

    public static async Task<int> Main(string[] args)
    {
        if (args.Length > 0 && args[0] == "--selftest") return SelfTest(args.Skip(1));
        return await SynthesisPipeline.Instance
            .AddPatch<ISkyrimMod, ISkyrimModGetter>(RunPatch)
            .SetAutogeneratedSettings("Settings", "settings.json", out _settings)
            .SetTypicalOpen(GameRelease.SkyrimSE, "ShaderMatchPatcher.esp")
            .Run(args);
    }

    private static readonly HashSet<string> OfficialMasters = new(StringComparer.OrdinalIgnoreCase)
        { "Skyrim.esm", "Update.esm", "Dawnguard.esm", "HearthFires.esm", "Dragonborn.esm" };

    private sealed class ManifestEntry
    {
        public string WrittenSha { get; set; } = "";
        public string CacheFile { get; set; } = "";
        /// <summary>True: the target mod's own file was edited. False: a copy was written to Destination.</summary>
        public bool InPlace { get; set; } = true;
        public string Destination { get; set; } = "";
    }

    /// <summary>Texture slots filled from files named after the diffuse: (slot, suffix, label).</summary>
    private static readonly (int slot, string suffix, string label)[] OwnTextures =
        [(1, "_n", "normal map"), (5, "_m", "environment mask")];

    public static void RunPatch(IPatcherState<ISkyrimMod, ISkyrimModGetter> state)
    {
        var settings = _settings.Value;
        if (settings.TargetMod.IsNull)
        {
            Console.WriteLine("ShaderMatch: no Target mod set in the patcher settings, nothing to do.");
            return;
        }
        var target = settings.TargetMod;
        if (!state.LoadOrder.ContainsKey(target))
        {
            Console.WriteLine($"ShaderMatch: {target} is not in the load order, nothing to do.");
            return;
        }

        var referencePlugins = new HashSet<ModKey>(settings.ExtraReferencePlugins);
        foreach (var listing in state.LoadOrder.ListedOrder)
        {
            var name = listing.ModKey.FileName.String;
            if (OfficialMasters.Contains(name) ||
                (settings.IncludeCreationClub && name.StartsWith("cc", StringComparison.OrdinalIgnoreCase)))
                referencePlugins.Add(listing.ModKey);
        }
        referencePlugins.Remove(target);

        // ---- which meshes, and what weapons use them
        var refMeshes = new Dictionary<string, WeaponContext>(StringComparer.OrdinalIgnoreCase);
        var targetMeshes = new Dictionary<string, WeaponContext>(StringComparer.OrdinalIgnoreCase);
        foreach (var weap in state.LoadOrder.PriorityOrder.Weapon().WinningOverrides())
        {
            Dictionary<string, WeaponContext> into;
            if (weap.FormKey.ModKey == target) into = targetMeshes;
            else if (referencePlugins.Contains(weap.FormKey.ModKey)) into = refMeshes;
            else continue;

            var paths = new List<(string path, bool firstPerson)>();
            if (weap.Model?.File is { IsNull: false } f) paths.Add((f.GivenPath, false));
            if (weap.FirstPersonModel.TryResolve(state.LinkCache, out var stat) &&
                stat.Model?.File is { IsNull: false } sf)
                paths.Add((sf.GivenPath, true));

            var materials = new List<string>();
            foreach (var kw in weap.Keywords ?? [])
                if (kw.TryResolve(state.LinkCache, out var k) &&
                    k.EditorID?.StartsWith("WeapMaterial", StringComparison.OrdinalIgnoreCase) == true)
                    materials.Add(k.EditorID);

            foreach (var (raw, firstPerson) in paths)
            {
                var mesh = MeshPath(raw);
                if (mesh.Length == 0) continue;
                if (!into.TryGetValue(mesh, out var ctx)) into[mesh] = ctx = new WeaponContext();
                if (firstPerson) ctx.UsedAsFirstPersonModel = true;
                else ctx.UsedAsWorldModel = true;
                if (weap.Data != null) ctx.Anims.Add(weap.Data.AnimationType);
                foreach (var m in materials) ctx.Materials.Add(m);
                if (weap.EditorID != null) ctx.Weapons.Add(weap.EditorID);
            }
        }
        // never patch a vanilla mesh, even if the target mod points at one
        foreach (var m in targetMeshes.Keys.Where(refMeshes.ContainsKey).ToList()) targetMeshes.Remove(m);

        Console.WriteLine($"ShaderMatch: target {target}: {targetMeshes.Count} weapon meshes. " +
                          $"Reference: {refMeshes.Count} meshes from {referencePlugins.Count} plugins.");
        if (targetMeshes.Count == 0) return;

        // ---- reference shapes, read live from the load order (loose files and archives)
        var reference = new List<RefShape>();
        var refUnreadable = 0;
        foreach (var (mesh, ctx) in refMeshes)
        {
            var bytes = ReadAsset(state, mesh);
            if (bytes == null) continue;
            try
            {
                var nif = new NifFile(bytes);
                foreach (var e in nif.Shaders())
                    if (e.Slots.Length > 0 && e.Slots[0].Trim().Length > 0)
                        reference.Add(new RefShape
                        {
                            Mesh = mesh, Shape = e.ShapeName, Shader = e.Shader, Slots = e.Slots, Context = ctx,
                        });
            }
            catch (NifException) { refUnreadable++; }
        }
        Console.WriteLine($"ShaderMatch: indexed {reference.Count} vanilla shapes" +
                          (refUnreadable > 0 ? $" ({refUnreadable} meshes unreadable)" : ""));

        // ---- cache of originals, so the patcher never treats its own output as the original
        var dataDir = state.ExtraSettingsDataPath?.Path
                      ?? Path.Combine(Path.GetDirectoryName(state.OutputPath.Path) ?? ".", "ShaderMatchData");
        var cacheDir = Path.Combine(dataDir, "OriginalsCache", Sanitize(target.FileName.String));
        var manifestPath = Path.Combine(cacheDir, "manifest.json");
        var manifest = File.Exists(manifestPath)
            ? JsonSerializer.Deserialize<Dictionary<string, ManifestEntry>>(File.ReadAllText(manifestPath))
              ?? new Dictionary<string, ManifestEntry>()
            : new Dictionary<string, ManifestEntry>();
        manifest = new Dictionary<string, ManifestEntry>(manifest, StringComparer.OrdinalIgnoreCase);
        var dataFolder = state.DataFolderPath.Path;

        if (settings.RestoreOriginals)
        {
            RestoreAll(manifest, dataFolder);
            SaveManifest(cacheDir, manifestPath, manifest);
            return;
        }

        // ---- where patched meshes go: in place, or a separate folder
        string? outputDir = null;
        var outSetting = settings.OutputFolder.Trim().Trim('"');
        if (outSetting.Length > 0)
        {
            var location = Path.GetFullPath(Path.IsPathRooted(outSetting) ? outSetting : Path.Combine(dataFolder, outSetting));
            outputDir = SamePath(location, dataFolder)
                ? null
                : Path.Combine(location, OriginalModName(location, target) + " Fixed Meshes");
        }
        var inPlace = outputDir == null;
        string Dest(string mesh) => Path.Combine(outputDir ?? dataFolder, mesh);
        Console.WriteLine(inPlace
            ? "ShaderMatch: editing the target mod's meshes in place."
            : $"ShaderMatch: writing patched meshes to {outputDir}");

        // undo earlier edits made to a different destination than the one now chosen
        var switched = 0;
        foreach (var (mesh, entry) in manifest.ToList())
        {
            if (entry.InPlace == inPlace && (inPlace || (entry.Destination.Length > 0 && SamePath(entry.Destination, Dest(mesh))))) continue;
            var result = Undo(mesh, entry, dataFolder);
            if (result != "restored") Console.WriteLine($"ShaderMatch: could not undo the earlier edit of {mesh}: {result}");
            manifest.Remove(mesh);
            switched++;
        }
        if (switched > 0)
        {
            SaveManifest(cacheDir, manifestPath, manifest);
            Console.WriteLine($"ShaderMatch: output destination changed, undid {switched} earlier edit(s).");
        }

        var assetExists = new Dictionary<string, bool>(StringComparer.OrdinalIgnoreCase);
        bool AssetExists(string path)
        {
            if (!assetExists.TryGetValue(path, out var e))
            {
                e = state.AssetProvider.TryGetStream(new DataRelativePath(path), out var s);
                s?.Dispose();
                assetExists[path] = e;
            }
            return e;
        }

        // ---- target shapes
        var nifs = new Dictionary<string, (NifFile nif, byte[] original, bool fromCache, string winnerSha)>(StringComparer.OrdinalIgnoreCase);
        var targets = new List<TargetShape>();
        var rows = new List<string[]>();
        foreach (var (mesh, ctx) in targetMeshes.OrderBy(k => k.Key))
        {
            var winner = ReadAsset(state, mesh);
            if (winner == null)
            {
                rows.Add([mesh, "", "", "SKIPPED", "mesh not found in the load order", "", ""]);
                continue;
            }
            if (inPlace && !File.Exists(Path.Combine(dataFolder, mesh)))
            {
                rows.Add([mesh, "", "", "SKIPPED",
                    "packed in an archive (BSA), not a loose file, so it can't be edited in place: extract it, " +
                    "or set an output folder to patch it",
                    "", ""]);
                continue;
            }
            var original = winner;
            var fromCache = false;
            if (manifest.TryGetValue(mesh, out var entry))
            {
                if (entry.WrittenSha == Sha(winner) && File.Exists(entry.CacheFile))
                {
                    original = File.ReadAllBytes(entry.CacheFile);
                    fromCache = true;
                }
                // in place, the mesh changed since we wrote it: treat the new one as original.
                // In an output folder the winner is simply the original (that folder isn't winning), and
                // the entry stays so the file written there can still be updated or removed.
                else if (inPlace) manifest.Remove(mesh);
            }
            try
            {
                var nif = new NifFile(original);
                nifs[mesh] = (nif, original, fromCache, Sha(winner));
                foreach (var e in nif.Shaders())
                    targets.Add(new TargetShape
                    {
                        Mesh = mesh, Block = e.Block, Shape = e.ShapeName, Original = e.Shader, Slots = e.Slots,
                        Context = ctx,
                    });
            }
            catch (NifException ex)
            {
                rows.Add([mesh, "", "", "SKIPPED", "unreadable: " + ex.Message, "", ""]);
            }
        }

        Matcher.Run(targets, reference, settings);

        // ---- apply and write back in place
        int updatedShapes = 0, writtenMeshes = 0, restored = 0, upToDate = 0;
        foreach (var (mesh, (nif, original, fromCache, winnerSha)) in nifs)
        {
            var any = false;
            foreach (var t in targets.Where(t => t.Mesh == mesh))
            {
                var shader = t.Original.Clone();
                var before = shader.Describe();
                var changes = t.Resolved ? shader.CopyMaterialFrom(t.Source!) : [];
                var newSlots = t.Slots.ToArray();
                var slotChanged = false;
                bool Empty(int i) => i >= newSlots.Length || newSlots[i].Trim().Length == 0;
                void SetSlot(int i, string value)
                {
                    if (newSlots.Length <= i) newSlots = [.. newSlots, .. Enumerable.Repeat("", i + 1 - newSlots.Length)];
                    newSlots[i] = value;
                    slotChanged = true;
                }

                // the mod's own _n / _m textures named after the diffuse, when their slot is empty
                if (settings.AddMatchingTextures && t.Diffuse.Length > 0 &&
                    !Matcher.SkipTexturePrefixes.Any(p => t.Diffuse.StartsWith(p)))
                {
                    var added = new List<string>();
                    foreach (var (slot, suffix, label) in OwnTextures)
                    {
                        if (!Empty(slot)) continue;
                        var found = SiblingTextures(t.Slots[0], suffix)
                            .FirstOrDefault(c => AssetExists(TextureSet.Normalize(c)));
                        if (found == null) continue;
                        SetSlot(slot, found);
                        added.Add($"{label} {Path.GetFileName(found)}");
                    }
                    if (added.Count > 0) changes.Add("added " + string.Join(", ", added));
                }

                // empty slots filled from the matched vanilla texture set
                if (t.Resolved && t.SourceSlots != null)
                {
                    var filled = new List<int>();
                    for (var i = 2; i < t.SourceSlots.Length; i++)
                        if (Empty(i) && t.SourceSlots[i].Trim().Length > 0)
                        {
                            SetSlot(i, t.SourceSlots[i]);
                            filled.Add(i);
                        }
                    if (filled.Count > 0) changes.Add("texture slots " + string.Join(",", filled));
                }

                if (changes.Count == 0)
                {
                    rows.Add(t.Resolved
                        ? [mesh, t.Shape, t.Diffuse, "already matches", t.Method, t.SourceLabel, ""]
                        : [mesh, t.Shape, t.Diffuse, t.Ambiguous != null ? "ambiguous" : t.Skipped ? "skipped" : "no match",
                            t.Note, "", ""]);
                    continue;
                }
                if (t.Resolved)
                {
                    var block = shader.ToBytes();
                    _ = new LightingShader(block); // re-parse check
                    nif.Blocks[t.Block] = block;
                }
                if (slotChanged)
                {
                    var ts = TextureSet.Build(newSlots);
                    if (!TextureSet.Parse(ts).SequenceEqual(newSlots)) throw new NifException("texture set rebuild failed");
                    nif.Blocks[t.Original.TextureSet] = ts;
                }
                var method = t.Resolved ? t.Method : "matching textures only, shader settings unchanged: " + t.Note;
                var change = $"{before} -> {shader.Describe()} ({string.Join(", ", changes)})";
                rows.Add([mesh, t.Shape, t.Diffuse, "UPDATED", method, t.SourceLabel, change]);
                if (!fromCache) Console.WriteLine($"UPDATED {mesh} [{t.Shape}]\n    {method}: {t.SourceLabel}\n    {change}");
                any = true;
            }

            var dest = Dest(mesh);
            if (any)
            {
                var bytes = nif.ToBytes();
                Verify(bytes, nif);
                var sha = Sha(bytes);
                var current = inPlace ? winnerSha : File.Exists(dest) ? Sha(File.ReadAllBytes(dest)) : "";
                if (inPlace && sha == current)
                {
                    upToDate++;  // already edited this way on an earlier run
                    continue;
                }
                // back up the original before the first edit, then record what we wrote
                Directory.CreateDirectory(cacheDir);
                var cacheFile = Path.Combine(cacheDir, Sanitize(mesh));
                if (!fromCache || !File.Exists(cacheFile)) File.WriteAllBytes(cacheFile, original);
                manifest[mesh] = new ManifestEntry
                {
                    WrittenSha = sha, CacheFile = cacheFile, InPlace = inPlace, Destination = inPlace ? "" : dest,
                };
                SaveManifest(cacheDir, manifestPath, manifest);
                if (sha == current)
                {
                    upToDate++;
                    continue;
                }
                updatedShapes += rows.Count(r => r[0] == mesh && r[3] == "UPDATED");
                if (inPlace) WriteInPlace(dest, bytes);
                else
                {
                    Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
                    File.WriteAllBytes(dest, bytes);
                }
                writtenMeshes++;
            }
            else if (manifest.TryGetValue(mesh, out var old))
            {
                // an earlier edit exists but nothing should change now: undo it
                if (Undo(mesh, old, dataFolder) == "restored") restored++;
                manifest.Remove(mesh);
            }
        }

        SaveManifest(cacheDir, manifestPath, manifest);
        var reportPath = Path.Combine(dataDir, $"ShaderMatchReport - {Sanitize(target.FileName.String)}.csv");
        WriteCsv(reportPath, rows);

        Console.WriteLine();
        foreach (var r in rows.Where(r => r[3] is "ambiguous" or "no match" or "SKIPPED"))
            Console.WriteLine($"NOT CHANGED {r[0]} [{r[1]}]: {r[4]}");
        Console.WriteLine($"\nShaderMatch: edited {updatedShapes} shader(s) in {writtenMeshes} mesh(es) of {target} " +
                          (inPlace ? "in place" : $"into {outputDir}") +
                          (upToDate > 0 ? $"; {upToDate} mesh(es) already up to date from an earlier run" : "") +
                          (restored > 0 ? $"; undid {restored} earlier edit(s) no longer needed" : "") + ".");
        Console.WriteLine($"ShaderMatch: originals backed up in {cacheDir}");
        Console.WriteLine($"ShaderMatch: report written to {reportPath}");
    }

    /// <summary>
    /// Overwrites an existing file's contents. Opening the existing file (rather than creating a new
    /// one) is what makes MO2's virtual file system write into the mod that owns the file instead of
    /// the overwrite folder.
    /// </summary>
    private static void WriteInPlace(string path, byte[] bytes)
    {
        using var fs = new FileStream(path, FileMode.Open, FileAccess.ReadWrite, FileShare.Read);
        fs.SetLength(0);
        fs.Write(bytes);
        fs.Flush(true);
    }

    /// <summary>
    /// Undoes one earlier edit: an in-place edit gets its original back from the backup, a mesh written
    /// to an output folder is deleted. Files changed by something else since are left alone.
    /// Returns "restored", "changed" or "missing".
    /// </summary>
    private static string Undo(string mesh, ManifestEntry entry, string dataFolder)
    {
        var dest = entry.InPlace ? Path.Combine(dataFolder, mesh) : entry.Destination;
        if (!File.Exists(dest)) return entry.InPlace ? "missing" : "restored";
        if (Sha(File.ReadAllBytes(dest)) != entry.WrittenSha) return "changed";
        if (entry.InPlace)
        {
            if (!File.Exists(entry.CacheFile)) return "missing";
            WriteInPlace(dest, File.ReadAllBytes(entry.CacheFile));
        }
        else File.Delete(dest);
        return "restored";
    }

    private static void RestoreAll(Dictionary<string, ManifestEntry> manifest, string dataFolder)
    {
        int restored = 0, changed = 0, missing = 0;
        foreach (var (mesh, entry) in manifest.ToList())
        {
            switch (Undo(mesh, entry, dataFolder))
            {
                case "missing":
                    missing++;
                    Console.WriteLine($"RESTORE skipped {mesh}: the mesh or its backup is gone");
                    continue;
                case "changed":
                    changed++;
                    Console.WriteLine($"RESTORE skipped {mesh}: changed since this patcher wrote it, left as it is");
                    break;
                default:
                    restored++;
                    break;
            }
            manifest.Remove(mesh);
        }
        Console.WriteLine($"ShaderMatch: restored {restored} mesh(es) to their originals" +
                          (changed > 0 ? $", {changed} had changed since and were left alone" : "") +
                          (missing > 0 ? $", {missing} could not be restored" : "") +
                          ". Turn 'Restore originals' off before the next run.");
    }

    private static void SaveManifest(string cacheDir, string manifestPath, Dictionary<string, ManifestEntry> manifest)
    {
        Directory.CreateDirectory(cacheDir);
        File.WriteAllText(manifestPath, JsonSerializer.Serialize(manifest, new JsonSerializerOptions { WriteIndented = true }));
    }

    /// <summary>Developer check: every .nif under the given folders must read and write back byte-for-byte.</summary>
    private static int SelfTest(IEnumerable<string> folders)
    {
        int ok = 0, bad = 0, shaders = 0;
        foreach (var folder in folders)
        foreach (var file in Directory.EnumerateFiles(folder, "*.nif", SearchOption.AllDirectories))
        {
            try
            {
                var data = File.ReadAllBytes(file);
                var nif = new NifFile(data);
                if (!nif.ToBytes().AsSpan().SequenceEqual(data)) throw new NifException("container round-trip differs");
                foreach (var e in nif.Shaders())
                {
                    if (!e.Shader.ToBytes().AsSpan().SequenceEqual(nif.Blocks[e.Block]))
                        throw new NifException("shader round-trip differs");
                    var clone = e.Shader.Clone();
                    if (clone.CopyMaterialFrom(e.Shader).Count != 0) throw new NifException("self-copy reported changes");
                    shaders++;
                }
                ok++;
            }
            catch (Exception ex)
            {
                bad++;
                Console.WriteLine($"FAIL {file}: {ex.Message}");
            }
        }
        Console.WriteLine($"selftest: {ok} ok, {bad} failed, {shaders} shaders");
        return bad == 0 ? 0 : 1;
    }

    /// <summary>
    /// Texture paths named after a diffuse with the given suffix, written the way the diffuse is:
    /// "textures\w\sword.dds" -> "textures\w\sword_n.dds"; a "_d" diffuse also tries without it.
    /// </summary>
    private static List<string> SiblingTextures(string diffuse, string suffix)
    {
        var raw = diffuse.Trim();
        if (!raw.EndsWith(".dds", StringComparison.OrdinalIgnoreCase)) return [];
        var stem = raw[..^4];
        var list = new List<string> { stem + suffix + ".dds" };
        if (stem.EndsWith("_d", StringComparison.OrdinalIgnoreCase)) list.Add(stem[..^2] + suffix + ".dds");
        return list;
    }

    /// <summary>
    /// The name of the mod the target plugin comes from: when the output location is an MO2 mods
    /// folder, the mod folder holding the plugin; otherwise the plugin's name without its extension.
    /// </summary>
    private static string OriginalModName(string location, ModKey target)
    {
        var plugin = target.FileName.String;
        try
        {
            if (Directory.Exists(location))
            {
                var owner = Directory.EnumerateDirectories(location)
                    .Where(d => !Path.GetFileName(d).EndsWith(" Fixed Meshes", StringComparison.OrdinalIgnoreCase))
                    .FirstOrDefault(d => File.Exists(Path.Combine(d, plugin)));
                if (owner != null) return Path.GetFileName(owner);
            }
        }
        catch (IOException) { }
        catch (UnauthorizedAccessException) { }
        return Sanitize(target.Name);
    }

    private static bool SamePath(string a, string b) =>
        string.Equals(Path.GetFullPath(a).TrimEnd('\\', '/'), Path.GetFullPath(b).TrimEnd('\\', '/'),
            StringComparison.OrdinalIgnoreCase);

    private static string MeshPath(string given)
    {
        var p = given.Trim().Replace('/', '\\').TrimStart('\\');
        if (p.Length == 0) return "";
        if (p.StartsWith("data\\", StringComparison.OrdinalIgnoreCase)) p = p[5..];
        if (!p.StartsWith("meshes\\", StringComparison.OrdinalIgnoreCase)) p = "meshes\\" + p;
        return p.ToLowerInvariant();
    }

    private static byte[]? ReadAsset(IPatcherState<ISkyrimMod, ISkyrimModGetter> state, string path)
    {
        if (!state.AssetProvider.TryGetStream(new DataRelativePath(path), out var stream)) return null;
        using (stream)
        using (var ms = new MemoryStream())
        {
            stream.CopyTo(ms);
            return ms.ToArray();
        }
    }

    private static void Verify(byte[] written, NifFile expected)
    {
        var check = new NifFile(written);
        if (check.NumBlocks != expected.NumBlocks || !check.ToBytes().AsSpan().SequenceEqual(written) ||
            check.Shaders().Count != expected.Shaders().Count)
            throw new NifException("verification of the patched mesh failed");
    }

    private static string Sha(byte[] b) => Convert.ToHexString(SHA256.HashData(b));

    private static string Sanitize(string s) =>
        string.Concat(s.Select(c => Path.GetInvalidFileNameChars().Contains(c) || c == '\\' || c == '/' ? '_' : c));

    private static void WriteCsv(string path, List<string[]> rows)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var sb = new StringBuilder("mesh,shape,diffuse,result,method / note,vanilla source,change\n");
        foreach (var r in rows)
            sb.AppendLine(string.Join(",", r.Select(v => "\"" + v.Replace("\"", "\"\"") + "\"")));
        File.WriteAllText(path, sb.ToString());
    }
}
